// Flatten cubic curves for deterministic PNG exports (64 segments per curve).
const polygons = contours.map(commands => {
  const result = []; let x = 0, y = 0;
  for (const [op,...p] of commands) {
    if (op === 'M' || op === 'L') { [x,y] = p; result.push([x,y]); }
    if (op === 'C') {
      const [x0,y0] = [x,y];
      for (let i=1;i<=64;i++) {
        const t=i/64, u=1-t;
        result.push([u**3*x0+3*u*u*t*p[0]+3*u*t*t*p[2]+t**3*p[4],u**3*y0+3*u*u*t*p[1]+3*u*t*t*p[3]+t**3*p[5]]);
      }
      [x,y] = p.slice(4);
    }
  }
  return result;
});
function inside(x,y,polygon) {
  let hit = false;
  for (let i=0,j=polygon.length-1;i<polygon.length;j=i++) {
    const [xi,yi]=polygon[i], [xj,yj]=polygon[j];
    if ((yi>y)!==(yj>y) && x < (xj-xi)*(y-yi)/(yj-yi)+xi) hit=!hit;
  }
  return hit;
}
